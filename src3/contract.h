#ifndef LAB5_CONTRACT_H
#define LAB5_CONTRACT_H

/* Function — имя типа указателя. Значение такого типа хранит адрес
   функции, принимающей один int и возвращающей float. */
typedef float (*Function)(int);

/* K — число членов Лейбница или пар множителей Валлиса.
   При K <= 0 возвращает NAN, так как контракт требует K >= 1. */
float Pi(int K);
/* x — показатель степени или последний индекс ряда, включая этот индекс.
   При x <= 0 возвращает NAN: степенная формула содержит 1/x. */
float E(int x);

#endif
